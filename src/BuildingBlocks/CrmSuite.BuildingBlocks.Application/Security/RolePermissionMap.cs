            [Roles.Installer] = InstallerPermissions,
            [Roles.Customer] = CustomerPermissions,
            [Roles.Reseller] = ResellerPermissions,
        };

    public static IReadOnlyCollection<string> For(string role) =>
        Map.TryGetValue(role, out var permissions) ? permissions : [];

    public static bool IsKnownRole(string role) => Map.ContainsKey(role);
